    /**
     * Returns inline JS for the classic editor regenerate button.
     *
     * WHY INLINE: This method is called from the `get_sample_permalink_html` filter, which
     * returns a string that WordPress concatenates directly into permalink HTML — there is no
     * enqueue hook available at this point in the request lifecycle. The required data
     * (REST URL, WP REST nonce, post ID, AI badge HTML) is post-specific and cannot be
     * pre-localized via wp_localize_script() without knowing the post context at enqueue time.
     * Extracting this to a static file would require a separate AJAX request just to fetch the
     * nonce, which is worse than a small inline script. Keep this inline intentionally.
     *
     * @param int $post_id The post ID.
     * @return string Script tag.
     */
    private function get_classic_regenerate_script( $post_id ) {
        $rest_url      = esc_url_raw( rest_url( 'haayal-ai-slug/v1/translate' ) );
        $nonce         = wp_create_nonce( 'wp_rest' );
        $post_id       = (int) $post_id;
        $ai_icon_svg   = '<svg aria-hidden="true" class="haayal-badge-icon" width="13" height="13" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><path d="M12 2C6.48 2 2 6.48 2 12s4.48 10 10 10 10-4.48 10-10S17.52 2 12 2m-2 15-5-5 1.41-1.41L10 14.17l7.59-7.59L19 8z"/></svg>';
        $ai_badge_html = wp_json_encode( $ai_icon_svg . esc_html__( 'Slug generated by AI', 'haayal-ai-slug-translator' ) );

        ob_start();
        ?>
        <script>
        (function(){
            var btn = document.getElementById('haayal-regen-btn');
            if (!btn) return;

            var origHTML        = btn.innerHTML;
            var translatingText = btn.getAttribute('data-translating');
            var alreadyBest     = btn.getAttribute('data-already-best');

            function showTooltip(message) {
                var tip = document.createElement('div');
                tip.className = 'haayal-slug-tooltip';
                tip.textContent = message;
                document.body.appendChild(tip);

                var rect = btn.getBoundingClientRect();
                var top  = rect.top - tip.offsetHeight - 6;
                if (top < 4) { top = rect.bottom + 6; }
                var left = rect.left + rect.width / 2 - tip.offsetWidth / 2;
                if (left < 4) { left = 4; }

                tip.style.top  = top + 'px';
                tip.style.left = left + 'px';

                setTimeout(function() {
                    tip.style.opacity = '0';
                    setTimeout(function() { if (tip.parentNode) { tip.parentNode.removeChild(tip); } }, 300);
                }, 3000);
            }

            btn.addEventListener('click', function(e) {
                e.preventDefault();
                if (btn.disabled) return;

                var titleEl = document.getElementById('title');
                if (!titleEl || !titleEl.value.trim()) return;

                var oldSlug = (document.getElementById('editable-post-name') || {}).textContent || '';

                btn.disabled = true;
                var icon = btn.querySelector('svg');
                if (icon) { icon.classList.add('haayal-icon-spin'); }
                btn.childNodes.forEach(function(n){ if (n.nodeType === 3) n.textContent = translatingText; });

                fetch('<?php echo esc_url( $rest_url ); ?>', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                        'X-WP-Nonce': '<?php echo esc_attr( $nonce ); ?>'
                    },
                    body: JSON.stringify({ title: titleEl.value.trim(), post_id: <?php echo absint( $post_id ); ?> })
                })
                .then(function(r){ return r.json(); })
                .then(function(data){
                    btn.disabled = false;
                    btn.innerHTML = origHTML;

                    if (data.slug) {
                        if (data.slug.trim() === oldSlug.trim()) {
                            showTooltip(alreadyBest);
                        } else {
                            // Update the hidden form input so the new slug is submitted on save.
                            var postNameInput = document.getElementById('post_name');
                            if (postNameInput) { postNameInput.value = data.slug; }
                            // Update the editable slug field.
                            var slugInput = document.getElementById('new-post-slug');
                            if (slugInput) { slugInput.value = data.slug; }
                            // Update the visible permalink display.
                            var editable = document.getElementById('editable-post-name');
                            if (editable) { editable.textContent = data.slug; }
                            var fullEl = document.getElementById('editable-post-name-full');
                            if (fullEl) { fullEl.textContent = data.slug; }
                            // Swap the badge back to "AI".
                            var indicator = document.querySelector('.ai-slug-indicator');
                            if (indicator) {
                                indicator.classList.remove('haayal-pill--edited');
                                indicator.classList.add('haayal-pill--ai');
                                indicator.innerHTML = <?php echo $ai_badge_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Value is wp_json_encode() of sanitized SVG + esc_html string. ?>;
                            }
                        }
                    }
                })
                .catch(function(){
                    btn.disabled = false;
                    btn.innerHTML = origHTML;
                });
            });
        })();
        </script>
        <?php
        return ob_get_clean();
    }


    /**
     * Enqueues shared CSS on classic editor (non-block) post screens.
     */
    public function enqueue_classic_editor_assets() {
        $screen = get_current_screen();
        if ( ! $screen || $screen->is_block_editor() || $screen->base !== 'post' ) {
            return;
        }
        wp_enqueue_style(
            'haayal-slug-shared',
            plugin_dir_url( dirname( __FILE__ ) ) . 'assets/css/ai-slug-shared.css',
            [],
            HAAYAL_AI_SLUG_TRANSLATOR_PLUGIN_VERSION
        );
    }

    /**
     * Enqueues the Gutenberg editor script for live slug translation.
     */
    public function enqueue_gutenberg_assets() {
        $screen = get_current_screen();
        if ( ! $screen || ! $screen->is_block_editor() ) {
            return;
        }

        $settings = Haayal_AI_Slug_Settings::get_settings();
        $post_type = $screen->post_type;

        // Only load for enabled post types.
        if ( ! in_array( $post_type, $settings['enabled_post_types'], true ) ) {
            return;
        }

        $post_id     = get_the_ID();
        $slug_source = $post_id ? get_post_meta( $post_id, '_slug_source', true ) : '';

        wp_enqueue_style(
            'haayal-slug-shared',
            plugin_dir_url( dirname( __FILE__ ) ) . 'assets/css/ai-slug-shared.css',
            [],
            HAAYAL_AI_SLUG_TRANSLATOR_PLUGIN_VERSION
        );

        wp_enqueue_script(
            'haayal-slug-gutenberg',
            plugin_dir_url( dirname( __FILE__ ) ) . 'assets/js/ai-slug-gutenberg.js',
            [ 'wp-data', 'wp-dom-ready', 'wp-api-fetch' ],
            HAAYAL_AI_SLUG_TRANSLATOR_PLUGIN_VERSION,
            true
        );

        $localize_data = [
            'slugSource' => $slug_source,
            'i18n'       => [
                'slugGeneratedByAi'  => __( 'Slug generated by AI', 'haayal-ai-slug-translator' ),
                'slugManuallyEdited' => __( 'Slug manually edited', 'haayal-ai-slug-translator' ),
                'regenerateSlug'     => __( 'Regenerate slug', 'haayal-ai-slug-translator' ),
                'translating'        => __( 'Translating…', 'haayal-ai-slug-translator' ),
                'alreadyBestOption'  => __( 'I tried, but this is already the best option', 'haayal-ai-slug-translator' ),
            ],
        ];

        if ( current_user_can( 'manage_options' ) ) {
            $localize_data['bulkUrl']  = admin_url( 'options-general.php?page=ai-slug-translator&tab=bulk' );
            $localize_data['i18n']['bulkTranslate'] = __( 'Bulk translate slugs', 'haayal-ai-slug-translator' );
        }

        wp_localize_script( 'haayal-slug-gutenberg', 'haayalGutenberg', $localize_data );
    }

    /**
     * Registers the REST API endpoint for slug translation.
     */
    public function register_translate_endpoint() {
        register_rest_route( 'haayal-ai-slug/v1', '/translate', [
            'methods'             => 'POST',
            'callback'            => [ $this, 'handle_translate_request' ],
            'permission_callback' => function () {
                return current_user_can( 'edit_posts' );
            },
        ] );
    }

    /**
     * Handles the REST API translation request from the Gutenberg editor.
     *
     * @param WP_REST_Request $request The REST request object.
     * @return WP_REST_Response The response with the translated slug.
     */
    public function handle_translate_request( $request ) {
        $title   = sanitize_text_field( $request->get_param( 'title' ) );
        $post_id = absint( $request->get_param( 'post_id' ) );

        if ( empty( $title ) ) {
            return new WP_REST_Response( [ 'error' => __( 'Title is empty.', 'haayal-ai-slug-translator' ) ], 400 );
        }

        $settings = Haayal_AI_Slug_Settings::get_settings();

        // Validate per-post capability and that the post type is enabled.
        if ( $post_id ) {
            if ( ! current_user_can( 'edit_post', $post_id ) ) {
                return new WP_REST_Response( [ 'error' => __( 'Permission denied.', 'haayal-ai-slug-translator' ) ], 403 );
            }
            $post = get_post( $post_id );
            if ( ! $post || ! in_array( $post->post_type, $settings['enabled_post_types'], true ) ) {
                return new WP_REST_Response( [ 'error' => __( 'Post type not enabled.', 'haayal-ai-slug-translator' ) ], 400 );
            }
        }

        $api_key = $settings['api_key'];

        Haayal_AI_Slug_Log::set_context( [ 'object_id' => $post_id, 'object_type' => 'post' ] );

        $slug = Haayal_AI_Slug_Helpers::translate_and_track( $title, $api_key, $settings['max_tokens'] ?? 20 );

        Haayal_AI_Slug_Log::set_context();

        if ( ! $slug ) {
            return new WP_REST_Response( [ 'error' => __( 'Translation failed or title is already in English.', 'haayal-ai-slug-translator' ) ], 422 );
        }

        // Store the generated slug in post meta if we have a valid post ID.
        if ( $post_id ) {
            update_post_meta( $post_id, '_generated_slug', $slug );
            update_post_meta( $post_id, '_slug_source', 'ai' );
        }

        return new WP_REST_Response( [ 'slug' => $slug ], 200 );
    }
