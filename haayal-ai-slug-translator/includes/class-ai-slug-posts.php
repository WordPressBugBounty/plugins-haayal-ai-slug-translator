            $regen_label  = esc_html__( 'Regenerate slug', 'haayal-ai-slug-translator' );
            $translating  = esc_attr__( 'Translating…', 'haayal-ai-slug-translator' );
            $already_best = esc_attr__( 'I tried, but this is already the best option', 'haayal-ai-slug-translator' );

            $regenerate  = '<span class="haayal-regen-wrap">';
            $regenerate .= '<button type="button" id="haayal-regen-btn" class="haayal-pill haayal-pill-regen" data-translating="' . $translating . '" data-already-best="' . $already_best . '">';
            $regenerate .= $regen_icon . $regen_label;
