class Haayal_AI_Slug_Posts {
    private $slug_meta_key = '_slug_source';

    
    public function __construct() {
        add_filter( 'wp_insert_post_data', [ $this, 'generate_slug_on_title_entry' ], 10, 2 );
        add_action( 'save_post', [ $this, 'track_slug_edits' ], 9, 2 );
        add_action( 'save_post', [ $this, 'sync_slug_on_save' ], 10 );
        add_filter( 'get_sample_permalink_html', [ $this, 'add_slug_indicator' ], 10, 5 );
        add_action( 'admin_enqueue_scripts', [ $this, 'enqueue_classic_editor_assets' ] );
        add_action( 'enqueue_block_editor_assets', [ $this, 'enqueue_gutenberg_assets' ] );
        add_action( 'rest_api_init', [ $this, 'register_translate_endpoint' ] );
    }

    /**
     * Generates and stores a slug after the title is entered.
     *
     * @param array $data An array of slashed post data.
     * @param array $postarr The raw post array.
     * @return array Modified post data with the AI-generated slug.
     */
    public function generate_slug_on_title_entry( $data, $postarr ) {

        // Skip autosave, revisions, or auto-drafts
        if ( wp_is_post_autosave( $postarr['ID'] ) || wp_is_post_revision( $postarr['ID'] ) || $data['post_status'] === 'auto-draft' ) {
            return $data;
        }

        // Check if the post type is supported
        $settings = Haayal_AI_Slug_Settings::get_settings();
        if ( ! in_array( $data['post_type'], $settings['enabled_post_types'], true ) ) {
            return $data;
        }

        // Skip if the slug is already manually set
        if ( ! empty( $postarr['post_name'] ) ) {
            return $data;
        }

        $existing_slug = get_post_meta( $postarr['ID'], '_generated_slug', true );
        $source = get_post_meta( $postarr['ID'], '_slug_source', true );

        if ( $existing_slug && $source === 'ai' ) {
            // Already generated by AI - Use it.
            $data['post_name'] = $existing_slug;
            return $data;
        }

        // For existing posts that already have a slug in the DB, don't overwrite.
        // Page builders (e.g. Bricks) do background saves that omit post_name; without
        // this guard the plugin would make an API call and replace the existing slug.
        if ( ! empty( $postarr['ID'] ) && get_post_field( 'post_name', $postarr['ID'] ) ) {
            return $data;
        }

        $title = $data['post_title'];

        // Generate a new slug using the AI
        $api_key = $settings['api_key'];

        Haayal_AI_Slug_Log::set_context( [ 'object_id' => $postarr['ID'], 'object_type' => 'post' ] );

        if ( empty( $title ) ) {
            Haayal_AI_Slug_Log::add_entry(
                __( 'Title is empty or missing.', 'haayal-ai-slug-translator' ),
                __( 'Unknown Title', 'haayal-ai-slug-translator' )
            );
            return $data;
        }
        
        $slug = Haayal_AI_Slug_Helpers::translate_and_track( $title, $api_key, $settings['max_tokens'] ?? 20 );

        if ( $slug ) {
            update_post_meta( $postarr['ID'], '_generated_slug', $slug );
            update_post_meta( $postarr['ID'], $this->slug_meta_key, 'ai' );
            $data['post_name'] = $slug;
        }

        Haayal_AI_Slug_Log::set_context();
        return $data;
    }

    /**
     * Ensures the slug matches the generated slug on save.
     *
     * @param int $post_id The ID of the post being saved.
     */
    public function sync_slug_on_save( $post_id ) {
        // Skip autosave, revisions, or auto-drafts
        if ( wp_is_post_autosave( $post_id ) || wp_is_post_revision( $post_id ) ) {
            return;
        }

        // Load the post object
        $post = get_post( $post_id );

        // Validate the post object
        if ( ! $post || $post->post_status === 'auto-draft' ) {
            return;
        }

        // Check if the post type is supported
        $settings = Haayal_AI_Slug_Settings::get_settings();
        if ( ! in_array( $post->post_type, $settings['enabled_post_types'], true ) ) {
            return;
        }

        // Retrieve the generated slug
        $generated_slug = get_post_meta( $post_id, '_generated_slug', true );
        $slug_source    = get_post_meta( $post_id, '_slug_source', true );

        // Only restore the AI slug if the user hasn't manually edited it.
        // track_slug_edits (priority 9) already ran by this point, so _slug_source
        // reflects the current state before we act on it.
        // Use a direct DB write instead of wp_update_post() to avoid triggering
        // a second save_post cycle, which causes page builders (e.g. Bricks) to
        // overwrite their freshly saved data with an empty second-pass request.
        if ( $generated_slug && $slug_source === 'ai' && $post->post_name !== $generated_slug ) {
            global $wpdb;
            $wpdb->update(
                $wpdb->posts,
                [ 'post_name' => $generated_slug ],
                [ 'ID'        => $post_id ],
                [ '%s' ],
                [ '%d' ]
            );
            clean_post_cache( $post_id );
        }
    }


    /**
     * Tracks slug edits and updates the meta key accordingly.
     *
     * @param int $post_id The ID of the post being saved.
     * @param WP_Post $post The post object.
     */
    public function track_slug_edits( $post_id, $post ) {
        // Skip autosave, revisions, or auto-drafts
        if ( wp_is_post_autosave( $post_id ) || wp_is_post_revision( $post_id ) ) {
            return;
        }

        // Retrieve the previous slug from the meta key
        $previous_slug = get_post_meta( $post_id, '_generated_slug', true );

        // If the slug has been edited by the user, update the meta key
        if ( $previous_slug && $post->post_name !== $previous_slug ) {
            update_post_meta( $post_id, '_slug_source', 'user-edited' );
        }
    }


    /**
     * Adds a custom indicator to the permalink HTML based on the slug source.
     *
     * @param string  $permalink_html The permalink HTML.
     * @param int     $post_id The post ID.
     * @param string  $new_title The new title.
     * @param string  $new_slug The new slug.
     * @param WP_Post $post The post object.
     * @return string The modified permalink HTML with the indicator.
     */
    public function add_slug_indicator( $permalink_html, $post_id, $new_title, $new_slug, $post ) {
        // Retrieve the slug source meta key
        $slug_source = get_post_meta( $post_id, '_slug_source', true );

        $ai_icon   = '<svg aria-hidden="true" class="haayal-badge-icon" width="13" height="13" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><path d="M12 2C6.48 2 2 6.48 2 12s4.48 10 10 10 10-4.48 10-10S17.52 2 12 2m-2 15-5-5 1.41-1.41L10 14.17l7.59-7.59L19 8z"/></svg>';
        $edit_icon = '<svg aria-hidden="true" class="haayal-badge-icon" width="13" height="13" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><path d="M3 17.25V21h3.75L17.81 9.94l-3.75-3.75zM20.71 7.04a1 1 0 0 0 0-1.41l-2.34-2.34a1 1 0 0 0-1.41 0l-1.83 1.83 3.75 3.75z"/></svg>';

        // When the user edits the slug via the AJAX call in the classic editor, $new_slug holds
        // the typed value before the post is saved. Treat it as user-edited immediately.
        $effective_source = $slug_source;
        if ( $slug_source === 'ai' && ! empty( $new_slug ) && $new_slug !== $post->post_name ) {
            $effective_source = 'user-edited';
        }

        if ( $effective_source === 'ai' ) {
            $indicator  = '<span class="ai-slug-indicator haayal-pill haayal-pill--ai">';
            $indicator .= $ai_icon . esc_html__( 'Slug generated by AI', 'haayal-ai-slug-translator' );
            $indicator .= '</span>';
        } elseif ( $effective_source === 'user-edited' ) {
            $indicator  = '<span class="ai-slug-indicator haayal-pill haayal-pill--edited">';
            $indicator .= $edit_icon . esc_html__( 'Slug manually edited', 'haayal-ai-slug-translator' );
            $indicator .= '</span>';
        } else {
            $indicator = '';
        }

        $settings = Haayal_AI_Slug_Settings::get_settings();

        // Add regenerate button for unpublished posts of enabled post types only,
        // and only when the title or slug contains non-Latin characters worth translating.
        $regenerate = '';
        if (
            in_array( $post->post_status, [ 'auto-draft', 'draft', 'pending' ], true ) &&
            in_array( $post->post_type, $settings['enabled_post_types'], true ) &&
            (
                Haayal_AI_Slug_Helpers::has_non_latin_chars( $new_title ) ||
                Haayal_AI_Slug_Helpers::has_non_latin_chars( $post->post_name )
            )
        ) {
