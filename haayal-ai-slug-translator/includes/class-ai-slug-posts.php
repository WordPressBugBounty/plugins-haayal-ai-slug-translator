            $bulk_url       = admin_url( 'options-general.php?page=ai-slug-translator&tab=bulk' );
            $bulk_label     = esc_html__( 'Bulk translate slugs', 'haayal-ai-slug-translator' );
            $external_icon  = '<svg aria-hidden="true" class="haayal-badge-icon" width="12" height="12" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><path d="M19 19H5V5h7V3H5a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7h-2zM14 3v2h3.59l-9.83 9.83 1.41 1.41L19 6.41V10h2V3z"/></svg>';
            $bulk_link  = '<a href="' . esc_url( $bulk_url ) . '" target="_blank" rel="noopener noreferrer" class="haayal-pill haayal-pill--bulk haayal-classic-bulk-link">';
